export function getBuddhistSyllabusCount(themeKey) {
  if (!themeKey) {
    return Object.values(BUDDHIST_SYLLABUS).reduce((sum, list) => sum + list.length, 0);
  }
  return (BUDDHIST_SYLLABUS[themeKey] || []).length;
}
